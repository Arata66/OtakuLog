CREATE TABLE anime (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    current_episode INTEGER,
    total_episodes INTEGER,
    status VARCHAR(20),
    score DOUBLE PRECISION,
    season VARCHAR(255),
    remark VARCHAR(255),
    cover_url VARCHAR(255),
    start_date DATE,
    end_date DATE,
    sort_order INTEGER,
    broadcast_day INTEGER,
    bangumi_id INTEGER,
    watch_start_date DATE,
    legacy BOOLEAN NOT NULL DEFAULT FALSE,
    watch_season VARCHAR(20),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT ck_anime_status CHECK (status IN ('WATCHING', 'FINISHED', 'PLANNING', 'DROPPED'))
);
CREATE INDEX idx_anime_name ON anime(name);
CREATE INDEX idx_anime_status ON anime(status);
CREATE INDEX idx_anime_broadcast_day ON anime(broadcast_day);
CREATE INDEX idx_anime_watch_season ON anime(watch_season);

CREATE TABLE tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);
CREATE TABLE anime_tag (
    anime_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    PRIMARY KEY (anime_id, tag_id),
    CONSTRAINT fk_at_anime FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE,
    CONSTRAINT fk_at_tag FOREIGN KEY (tag_id) REFERENCES tag(id) ON DELETE CASCADE
);
CREATE INDEX idx_anime_tag_tag_id ON anime_tag(tag_id);

CREATE TABLE anime_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    color VARCHAR(20),
    sort_order INTEGER DEFAULT 0,
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6)
);
CREATE TABLE anime_group_relation (
    group_id BIGINT NOT NULL,
    anime_id BIGINT NOT NULL,
    PRIMARY KEY (group_id, anime_id),
    CONSTRAINT fk_agr_group FOREIGN KEY (group_id) REFERENCES anime_group(id) ON DELETE CASCADE,
    CONSTRAINT fk_agr_anime FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE
);

CREATE TABLE episode_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT NOT NULL,
    episode_number INTEGER NOT NULL,
    watched_date DATE,
    record_source VARCHAR(20) NOT NULL DEFAULT 'LEGACY',
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT uk_anime_episode UNIQUE (anime_id, episode_number),
    CONSTRAINT fk_er_anime FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE
);
CREATE INDEX idx_er_watched_date ON episode_record(watched_date);

CREATE TABLE anime_memory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT NOT NULL,
    memory_key VARCHAR(36) NOT NULL,
    content TEXT NOT NULL,
    liked TEXT,
    disliked TEXT,
    scope VARCHAR(200),
    context VARCHAR(20) NOT NULL,
    watched_date DATE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_am_memory_key UNIQUE (memory_key),
    CONSTRAINT fk_am_anime FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE
);
CREATE INDEX idx_am_anime_created ON anime_memory(anime_id, created_at, id);


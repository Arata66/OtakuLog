    origin VARCHAR(20) NOT NULL,
    ai_call_key VARCHAR(36),
    suggested_quote_field VARCHAR(20),
    suggested_quote VARCHAR(800),
    suggested_statement VARCHAR(500),
    suggested_direction VARCHAR(20),
    suggested_aspect VARCHAR(20),
    suggested_factor VARCHAR(100),
